<script lang="ts">
  import ChevronRightIcon from "@lucide/svelte/icons/chevron-right";
  import DatabaseIcon from "@lucide/svelte/icons/database";
  import LayersIcon from "@lucide/svelte/icons/layers";
  import CornerLeftUpIcon from "@lucide/svelte/icons/corner-left-up";
  import FileJsonIcon from "@lucide/svelte/icons/file-json";
  import PencilIcon from "@lucide/svelte/icons/pencil";
  import EyeIcon from "@lucide/svelte/icons/eye";
  import CircleDashedIcon from "@lucide/svelte/icons/circle-dashed";
  import clsx from "clsx";

  import TreeNode from "./TreeNode.svelte";
  import {
    isAncestor,
    nodeName,
    nodeSource,
    type EditorNode,
    type EditorStore,
  } from "./editor.svelte";

  const {
    node,
    store,
    depth = 0,
    filter = "",
    onselect,
  }: {
    node: EditorNode;
    store: EditorStore;
    depth?: number;
    filter?: string;
    onselect: (node: EditorNode) => void;
  } = $props();

  let manuallyOpen = $state<boolean | undefined>();

  const info = $derived.by(() => {
    void store.version;
    const source = nodeSource(node);
    return {
      name: nodeName(node),
      total: node.total,
      own: node.own,
      ambiguous: node.ambiguous,
      children: [...node.children],
      source,
      origin: node.origin,
      modified: node.isNew || node.changedConfigs.size > 0 || node.origin === "edited",
    };
  });

  const selected = $derived(store.selected === node);
  const containsSelected = $derived(isAncestor(node, store.selected));
  const open = $derived(manuallyOpen ?? (depth < 1 || containsSelected || filter !== ""));

  function matches(n: EditorNode, f: string): boolean {
    if (nodeName(n).toLowerCase().includes(f) || n.slug.includes(f)) return true;
    return n.children.some((c) => matches(c, f));
  }
  const visible = $derived.by(() => {
    void store.version;
    return filter === "" || matches(node, filter.toLowerCase());
  });

  const isLeaf = $derived(info.children.length === 0);
  const tooBig = $derived(isLeaf && info.total > store.threshold);

  function sourceTitle() {
    if (info.origin === "edited") return "Boundary edited here: will be exported as boundary.geojson";
    if (info.origin === "preview") return "Boundary from a query run here: regenerated by the pipeline";
    if (info.origin === "manual") return "Manual boundary.geojson";
    if (info.source.delegateTo) return `Generated by ${info.source.delegateTo}`;
    if (info.source.query) return "Overpass query";
    if (info.source.multiples.length) return "Container: its query generates the children";
    if (info.origin === "generated") return "Generated by the query of the parent";
    return "No boundary";
  }

  let row: HTMLDivElement | undefined = $state();
  $effect(() => {
    if (selected) row?.scrollIntoView({ block: "nearest" });
  });
</script>

{#if visible}
  <div
    bind:this={row}
    role="treeitem"
    aria-selected={selected}
    tabindex="-1"
    class={clsx(
      "group flex h-7 cursor-pointer items-center gap-1 rounded-sm pr-2 text-sm hover:bg-muted",
      selected && "bg-accent font-medium ring-1 ring-ring/40",
    )}
    style:padding-left="{depth * 14 + 2}px"
    onclick={() => onselect(node)}
    onkeydown={(e) => e.key === "Enter" && onselect(node)}
  >
    <button
      class={clsx("rounded-sm p-0.5 hover:bg-background", isLeaf && "invisible")}
      aria-label={open ? "Collapse" : "Expand"}
      onclick={(e) => {
        e.stopPropagation();
        manuallyOpen = !open;
      }}
    >
      <ChevronRightIcon class={clsx("size-3.5 transition-transform", open && "rotate-90")} />
    </button>

    <span class="shrink-0 text-muted-foreground" title={sourceTitle()}>
      {#if info.origin === "edited"}
        <PencilIcon class="size-3.5 text-blue-600" />
      {:else if info.origin === "preview"}
        <EyeIcon class="size-3.5 text-rose-600" />
      {:else if info.origin === "manual"}
        <FileJsonIcon class="size-3.5" />
      {:else if info.source.delegateTo}
        <CornerLeftUpIcon class="size-3.5" />
      {:else if info.source.query}
        <DatabaseIcon class="size-3.5" />
      {:else if info.source.multiples.length}
        <LayersIcon class="size-3.5" />
      {:else if info.origin === "generated"}
        <CornerLeftUpIcon class="size-3.5" />
      {:else}
        <CircleDashedIcon class="size-3.5 opacity-50" />
      {/if}
    </span>

    <span class="truncate">{info.name}</span>
    {#if info.modified}
      <span class="size-1.5 shrink-0 rounded-full bg-blue-600" title="Modified"></span>
    {/if}

    <span class="ml-auto flex shrink-0 items-center gap-1 text-xs tabular-nums">
      {#if info.ambiguous > 0}
        <span class="text-amber-600" title="Places inside overlapping regions">⚠{info.ambiguous}</span>
      {/if}
      {#if !isLeaf && info.own > 0}
        <span class="text-rose-600" title="Places in this region but not in any of its children">
          +{info.own}
        </span>
      {/if}
      <span
        class={clsx(
          "rounded px-1",
          tooBig ? "bg-amber-100 text-amber-800 dark:bg-amber-900 dark:text-amber-100" : "text-muted-foreground",
          info.total === 0 && "opacity-40",
        )}
        title={tooBig
          ? `More than ${store.threshold} places: consider subdividing`
          : "Climbing places in this region"}
      >
        {info.total}
      </span>
    </span>
  </div>

  {#if open}
    {#each info.children as child (child.id)}
      <TreeNode node={child} {store} depth={depth + 1} {filter} {onselect} />
    {/each}
  {/if}
{/if}
