import type { Position } from "geojson";
import type { ClimbingPoint, ClimbingPointKind } from "@climbhub/climbing-data-gen";
import type { YamlConfig } from "@climbhub/reverse-geocoding-data";

import {
  bboxContains,
  bboxIntersects,
  boundaryPolygons,
  cloneBoundary,
  countVertices,
  emptyBBox,
  isEmptyBBox,
  mergeBBox,
  polygonsContain,
  positionKey,
  preparePolygons,
  ringsBBox,
  sharedVertexIndex,
  simplifyBoundary,
  type BBox,
  type PreparedPolygon,
} from "./geometry";
import type { Boundary, ConfigFile, ServerTreeNode } from "./types";

/**
 * Where the boundary of a node comes from.
 * - `manual`: data/<path>/boundary.geojson, committed.
 * - `generated`: output/<path>/boundary.geojson, generated by an overpass query.
 * - `edited`: modified in the editor. Will be exported as a manual boundary.
 * - `preview`: result of an overpass query run in the editor. Will be regenerated by the pipeline.
 */
export type BoundaryOrigin = "manual" | "generated" | "edited" | "preview";

export interface EditorNode {
  id: number;
  slug: string;
  parent?: EditorNode;
  children: EditorNode[];
  configs: ConfigFile[];
  /** Config files whose content changed, and need to be written again */
  changedConfigs: Set<string>;
  boundary?: Boundary;
  origin?: BoundaryOrigin;
  /** Created in the editor */
  isNew: boolean;

  // Caches, updated by `updateGeometryCache`
  prepared: PreparedPolygon[];
  ownBBox: BBox;
  /** Own bbox merged with the children ones, as `_bbox` in hierarchy-index.json */
  bbox: BBox;
  vertexCount: number;

  // Statistics, updated by `recomputeStats`
  /** Climbing places geolocated in this node or its descendants */
  total: number;
  /** Climbing places geolocated in this node itself, not a child */
  own: number;
  /** Climbing places of the subtree inside several overlapping siblings */
  ambiguous: number;
  kinds: Record<ClimbingPointKind, number>;
}

/** Above this, the vertices are not displayed on the map: simplify the boundary first */
export const MAX_EDITABLE_VERTICES = 30000;

export const KINDS: ClimbingPointKind[] = ["crag", "area", "boulder", "gym", "other"];

/** Status of a climbing place, as displayed on the map */
export const PointStatus = {
  Assigned: 0,
  /** Not inside any boundary: the pipeline will drop it */
  Unassigned: 1,
  /** Inside several sibling boundaries: the first one alphabetically wins */
  Ambiguous: 2,
} as const;

interface UndoEntry {
  label: string;
  nodes: { node: EditorNode; boundary?: Boundary; origin?: BoundaryOrigin }[];
}

function emptyKinds(): Record<ClimbingPointKind, number> {
  return { crag: 0, area: 0, boulder: 0, gym: 0, other: 0 };
}

/** Same order as `readdirSync`, used by the pipeline: the first matching sibling wins */
function bySlug(a: EditorNode, b: EditorNode) {
  return a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0;
}

export function nodePath(node: EditorNode): string {
  return node.parent ? `${nodePath(node.parent)}/${node.slug}` : node.slug;
}

export function nodeName(node: EditorNode): string {
  const displayName = node.configs.find((c) => c.config.displayName)?.config.displayName;
  if (displayName) return displayName;
  const properties = node.boundary?.features[0]?.properties;
  return properties?.official_name || properties?.name || node.slug;
}

export function isAncestor(ancestor: EditorNode, node: EditorNode | undefined): boolean {
  for (let n = node?.parent; n; n = n.parent) if (n === ancestor) return true;
  return false;
}

export function* walk(node: EditorNode): Generator<EditorNode> {
  yield node;
  for (const child of node.children) yield* walk(child);
}

/** Describes how the boundary of a node is obtained. */
export function nodeSource(node: EditorNode) {
  const main = node.configs.find((c) => c.file === "config.yaml")?.config;
  const multiples = node.configs.filter((c) => c.config.multiple);
  return {
    query: main?.query && !main.multiple ? main.query : undefined,
    delegateTo: main?.delegateTo,
    multiples,
  };
}

export class EditorStore {
  /** Bumped on every change. Read it in a $derived to react to changes of the (non reactive) tree. */
  version = $state(0);
  selected = $state.raw<EditorNode | undefined>();
  /** Nodes whose vertices are being edited on the map */
  editing = $state(false);
  /** Move the vertices shared with the neighbouring boundaries together */
  linkVertices = $state(true);
  /** Leaves with more climbing places than this should probably be subdivided */
  threshold = $state(150);
  /** Preview of an operation (simplification, query result...), drawn on top of the map */
  preview = $state.raw<Boundary | undefined>();
  undoStack = $state.raw<UndoEntry[]>([]);
  /** Bumped when the climbing places are replaced */
  pointsVersion = $state(0);

  root: EditorNode;
  nodesById = new Map<number, EditorNode>();
  /** Paths of the nodes removed in the editor */
  removedPaths = new Set<string>();
  /** Paths whose generated boundary in output/ is stale, because their query changed */
  stalePaths = new Set<string>();

  // Climbing places, as flat arrays for speed
  points: ClimbingPoint[] = [];
  lon = new Float64Array();
  lat = new Float64Array();
  /** Id of the node each point is geolocated in, -1 if none */
  assignment = new Int32Array();
  status = new Uint8Array();
  /** Called with the indexes of the points whose status changed */
  onPointsChanged?: (indexes: number[]) => void;

  private nextId = 0;

  constructor(tree: ServerTreeNode, points: ClimbingPoint[]) {
    this.root = this.importNode(tree);
    this.updateBBoxes(this.root);
    this.setPoints(points);
  }

  private importNode(tree: ServerTreeNode, parent?: EditorNode): EditorNode {
    const node = this.createNode(tree.slug, parent, tree.configs);
    node.boundary = tree.boundary;
    node.origin = tree.boundarySource;
    node.children = tree.children.map((child) => this.importNode(child, node));
    this.updateGeometryCache(node);
    return node;
  }

  private createNode(slug: string, parent: EditorNode | undefined, configs: ConfigFile[] = []) {
    const node: EditorNode = {
      id: this.nextId++,
      slug,
      parent,
      children: [],
      configs,
      changedConfigs: new Set(),
      isNew: false,
      prepared: [],
      ownBBox: emptyBBox(),
      bbox: emptyBBox(),
      vertexCount: 0,
      total: 0,
      own: 0,
      ambiguous: 0,
      kinds: emptyKinds(),
    };
    this.nodesById.set(node.id, node);
    return node;
  }

  private updateGeometryCache(node: EditorNode) {
    const polygons = boundaryPolygons(node.boundary);
    node.prepared = preparePolygons(polygons);
    node.ownBBox = ringsBBox(polygons);
    node.vertexCount = countVertices(node.boundary);
  }

  /** Recomputes the bboxes of the subtree */
  private updateBBoxes(node: EditorNode): BBox {
    node.bbox = node.children.reduce((b, child) => mergeBBox(b, this.updateBBoxes(child)), {
      ...node.ownBBox,
    });
    return node.bbox;
  }

  /** Recomputes the bboxes of the node and its ancestors */
  private updateAncestorBBoxes(node: EditorNode) {
    for (let n: EditorNode | undefined = node; n; n = n.parent) {
      n.bbox = n.children.reduce((b, child) => mergeBBox(b, child.bbox), { ...n.ownBBox });
    }
  }

  // ---------------------------------------------------------------------------------------------
  // Geolocation of the climbing places, mirroring ReverseGeolocator of @climbhub/climbing-data-gen
  // ---------------------------------------------------------------------------------------------

  setPoints(points: ClimbingPoint[]) {
    this.points = points;
    this.lon = Float64Array.from(points, (p) => p.lon);
    this.lat = Float64Array.from(points, (p) => p.lat);
    this.assignment = new Int32Array(points.length).fill(-1);
    this.status = new Uint8Array(points.length);
    this.recompute();
    this.pointsVersion++;
    this.version++;
  }

  private geolocate(node: EditorNode, lon: number, lat: number): EditorNode | undefined {
    if (!bboxContains(node.bbox, lon, lat)) return;
    for (const child of node.children) {
      const matched = this.geolocate(child, lon, lat);
      if (matched) return matched;
    }
    if (polygonsContain(node.prepared, lon, lat)) return node;
  }

  /** Whether the point is inside several siblings along its geolocation path */
  private isAmbiguous(assigned: EditorNode, lon: number, lat: number) {
    for (let n: EditorNode | undefined = assigned; n?.parent; n = n.parent) {
      for (const sibling of n.parent.children) {
        if (sibling !== n && this.geolocate(sibling, lon, lat)) return true;
      }
    }
    return false;
  }

  /** Geolocates again the points inside `area`, or all of them. */
  recompute(area?: BBox) {
    const changed: number[] = [];
    for (let i = 0; i < this.points.length; i++) {
      const lon = this.lon[i]!,
        lat = this.lat[i]!;
      if (area && !bboxContains(area, lon, lat)) continue;

      const node = this.geolocate(this.root, lon, lat);
      this.assignment[i] = node ? node.id : -1;
      const status = !node
        ? PointStatus.Unassigned
        : this.isAmbiguous(node, lon, lat)
          ? PointStatus.Ambiguous
          : PointStatus.Assigned;
      if (status !== this.status[i]) changed.push(i);
      this.status[i] = status;
    }
    this.recomputeStats();
    if (changed.length) this.onPointsChanged?.(changed);
  }

  private recomputeStats() {
    for (const node of this.nodesById.values()) {
      node.total = node.own = node.ambiguous = 0;
      node.kinds = emptyKinds();
    }
    for (let i = 0; i < this.points.length; i++) {
      const node = this.nodesById.get(this.assignment[i]!);
      if (!node) continue;
      node.own++;
      const kind = this.points[i]!.kind;
      const ambiguous = this.status[i] === PointStatus.Ambiguous;
      for (let n: EditorNode | undefined = node; n; n = n.parent) {
        n.total++;
        n.kinds[kind]++;
        if (ambiguous) n.ambiguous++;
      }
    }
  }

  get unassignedCount() {
    let count = 0;
    for (const s of this.status) if (s === PointStatus.Unassigned) count++;
    return count;
  }

  get ambiguousCount() {
    let count = 0;
    for (const s of this.status) if (s === PointStatus.Ambiguous) count++;
    return count;
  }

  /** Unassigned points inside a bbox */
  unassignedIn(b: BBox) {
    let count = 0;
    for (let i = 0; i < this.points.length; i++) {
      if (this.status[i] === PointStatus.Unassigned && bboxContains(b, this.lon[i]!, this.lat[i]!))
        count++;
    }
    return count;
  }

  // ---------------------------------------------------------------------------------------------
  // Geometry edits
  // ---------------------------------------------------------------------------------------------

  private pushUndo(label: string, nodes: EditorNode[]) {
    const entry: UndoEntry = {
      label,
      nodes: nodes.map((node) => ({
        node,
        boundary: cloneBoundary(node.boundary),
        origin: node.origin,
      })),
    };
    this.undoStack = [...this.undoStack.slice(-49), entry];
  }

  /**
   * Call before modifying the boundaries of `nodes` in place, then call the returned function
   * once done. Used by the vertex dragging, which modifies the boundaries continuously.
   */
  beginEdit(label: string, nodes: EditorNode[]) {
    this.pushUndo(label, nodes);
    const before = nodes.map((n) => ({ ...n.ownBBox }));
    return (origin: BoundaryOrigin = "edited") => this.afterEdit(nodes, before, origin);
  }

  private afterEdit(nodes: EditorNode[], before: BBox[], origin: BoundaryOrigin) {
    let area = emptyBBox();
    nodes.forEach((node, i) => {
      node.origin = origin;
      area = mergeBBox(area, before[i]!);
      this.updateGeometryCache(node);
      area = mergeBBox(area, node.ownBBox);
      this.updateAncestorBBoxes(node);
    });
    if (!isEmptyBBox(area)) this.recompute(area);
    this.version++;
  }

  setBoundary(node: EditorNode, boundary: Boundary | undefined, origin: BoundaryOrigin, label: string) {
    const done = this.beginEdit(label, [node]);
    node.boundary = boundary;
    done(origin);
  }

  undo() {
    const entry = this.undoStack.at(-1);
    if (!entry) return;
    this.undoStack = this.undoStack.slice(0, -1);
    let area = emptyBBox();
    for (const { node, boundary, origin } of entry.nodes) {
      area = mergeBBox(area, node.ownBBox);
      node.boundary = boundary;
      node.origin = origin;
      this.updateGeometryCache(node);
      area = mergeBBox(area, node.ownBBox);
      this.updateAncestorBBoxes(node);
    }
    if (!isEmptyBBox(area)) this.recompute(area);
    this.version++;
  }

  /** Nodes whose boundaries may share vertices with `node`: everything except its ancestors and descendants. */
  neighbours(node: EditorNode, area: BBox): EditorNode[] {
    const result: EditorNode[] = [];
    for (const other of this.nodesById.values()) {
      if (other === node || !other.boundary) continue;
      if (isAncestor(other, node) || isAncestor(node, other)) continue;
      if (bboxIntersects(other.ownBBox, area)) result.push(other);
    }
    return result;
  }

  /**
   * Simplifies the boundaries of `nodes`. Shared borders between them stay shared. When
   * `lockNeighbours` is set, the vertices shared with boundaries outside of `nodes` are kept,
   * so that no gap appears with them.
   */
  simplified(nodes: EditorNode[], tolerance: number, lockNeighbours: boolean) {
    const withBoundary = nodes.filter((n) => n.boundary);
    const area = withBoundary.reduce((b, n) => mergeBBox(b, n.ownBBox), emptyBBox());
    const group = new Set(withBoundary);
    const neighbours = new Set<EditorNode>();
    for (const node of withBoundary) {
      for (const n of this.neighbours(node, area)) if (!group.has(n)) neighbours.add(n);
    }

    const index = sharedVertexIndex(
      [...group, ...neighbours].map((n) => ({ id: String(n.id), boundary: n.boundary! })),
    );
    const groupIds = new Set([...group].map((n) => String(n.id)));
    const sharers = (p: Position) => [...(index.get(positionKey(p)) ?? [])].sort().join(",");
    const locked = (p: Position) => {
      if (!lockNeighbours) return false;
      for (const id of index.get(positionKey(p)) ?? []) if (!groupIds.has(id)) return true;
      return false;
    };

    return withBoundary.map((node) => ({
      node,
      boundary: simplifyBoundary(node.boundary!, { tolerance, sharers, locked }),
    }));
  }

  applySimplification(result: { node: EditorNode; boundary: Boundary }[]) {
    const done = this.beginEdit(
      "Simplify",
      result.map((r) => r.node),
    );
    for (const { node, boundary } of result) node.boundary = boundary;
    done();
  }

  // ---------------------------------------------------------------------------------------------
  // Structure and configuration edits
  // ---------------------------------------------------------------------------------------------

  addChild(parent: EditorNode, slug: string, displayName?: string, boundary?: Boundary) {
    if (parent.children.some((c) => c.slug === slug)) {
      throw new Error(`${nodePath(parent)}/${slug} already exists`);
    }
    const node = this.createNode(slug, parent);
    node.isNew = true;
    if (displayName) this.setConfig(node, "config.yaml", { displayName });
    parent.children.push(node);
    parent.children.sort(bySlug);
    this.removedPaths.delete(nodePath(node));
    if (boundary) {
      node.boundary = boundary;
      node.origin = "edited";
      this.updateGeometryCache(node);
    }
    this.updateAncestorBBoxes(node);
    this.recompute(node.bbox);
    this.version++;
    return node;
  }

  removeNode(node: EditorNode) {
    this.detach(node);
    this.recompute();
    this.version++;
  }

  private detach(node: EditorNode) {
    const parent = node.parent;
    if (!parent) return;
    for (const n of walk(node)) {
      this.nodesById.delete(n.id);
      this.removedPaths.add(nodePath(n));
    }
    parent.children = parent.children.filter((c) => c !== node);
    this.updateAncestorBBoxes(parent);
    if (this.selected && (this.selected === node || isAncestor(node, this.selected))) {
      this.selected = parent;
    }
    this.undoStack = this.undoStack.filter((e) => e.nodes.every((n) => this.nodesById.has(n.node.id)));
  }

  /**
   * Whether removing the node is meaningful: the children generated by a `multiple` query of the
   * parent would come back. Remove the query of the parent instead.
   */
  canRemove(node: EditorNode) {
    if (!node.parent) return false;
    if (nodeSource(node.parent).multiples.length === 0) return true;
    const delegates = node.configs.some((c) => c.config.delegateTo);
    return !delegates && node.origin !== "generated" && node.origin !== "preview";
  }

  setConfig(node: EditorNode, file: string, patch: Partial<YamlConfig>) {
    let configFile = node.configs.find((c) => c.file === file);
    if (!configFile) {
      configFile = { file, config: {} };
      node.configs.push(configFile);
      node.configs.sort((a, b) =>
        a.file === "config.yaml" ? -1 : b.file === "config.yaml" ? 1 : a.file.localeCompare(b.file),
      );
    }
    const config = { ...configFile.config, ...patch };
    for (const key of Object.keys(config) as (keyof YamlConfig)[]) {
      if (config[key] === undefined || config[key] === "" || config[key] === false) delete config[key];
    }
    if (patch.query !== undefined && patch.query !== configFile.config.query) {
      // The pipeline only runs a query when there is no boundary in output/
      if (config.multiple) for (const child of node.children) this.stalePaths.add(nodePath(child));
      else this.stalePaths.add(nodePath(node));
    }
    configFile.config = config;
    node.changedConfigs.add(file);
    this.version++;
  }

  /**
   * Removes a config file. For a `multiple` query, also removes the children it generates, except
   * the ones with a boundary edited by hand, which only lose their `delegateTo`.
   */
  removeConfig(node: EditorNode, file: string) {
    const removed = node.configs.find((c) => c.file === file);
    node.configs = node.configs.filter((c) => c !== removed);
    node.changedConfigs.add(file);
    if (removed?.config.multiple) {
      for (const child of [...node.children]) {
        const delegate = child.configs.find((c) => c.config.delegateTo === `../${file}`);
        const generated = child.origin === "generated" || child.origin === "preview";
        if (generated && (delegate || !child.configs.length)) this.detach(child);
        else if (delegate) this.setConfig(child, delegate.file, { delegateTo: undefined });
      }
      this.recompute();
    }
    this.version++;
  }

  /**
   * Applies the result of a `multiple: true` query of `parent`: creates the missing children
   * (delegating to the query), and previews the new boundaries of the existing ones.
   * Boundaries edited by hand are kept.
   */
  applyMultipleResult(parent: EditorNode, file: string, children: Map<string, Boundary>) {
    const existing = new Map(parent.children.map((c) => [c.slug, c]));
    const touched: EditorNode[] = [];
    const created: EditorNode[] = [];
    for (const slug of children.keys()) {
      const child = existing.get(slug);
      if (child) {
        if (child.origin !== "manual" && child.origin !== "edited") touched.push(child);
      } else {
        const node = this.createNode(slug, parent);
        node.isNew = true;
        this.setConfig(node, "config.yaml", { delegateTo: `../${file}` });
        parent.children.push(node);
        created.push(node);
      }
    }
    parent.children.sort(bySlug);

    const done = this.beginEdit("Run query", [...touched, ...created]);
    for (const node of [...touched, ...created]) node.boundary = children.get(node.slug);
    done("preview");
    return { created: created.length, updated: touched.length };
  }

  /** Every node whose export would differ from what is in data/ */
  get modifiedNodes(): EditorNode[] {
    return [...walk(this.root)].filter(
      (n) => n.isNew || n.changedConfigs.size > 0 || n.origin === "edited",
    );
  }
}
