// Generates src/lib/data/region-names.svelte.js for wuchale from reverse-geocoding-data's region-names.json,
// and fills the catalogs of the other languages with the OSM names. Run `bun run region-names`,
// then `bunx wuchale` to extract the messages, then run it again to fill the catalogs.
import { existsSync, readFileSync, writeFileSync } from "fs";

const names: { path: string; en: string; de: string; fr: string; es: string; it: string; pt: string }[] = JSON.parse(
  readFileSync(`${import.meta.dirname}/../../reverse-geocoding-data/output/region-names.json`, "utf8"),
);

const items = names.map((n) => `    ${JSON.stringify(n.en)},`).join("\n");
writeFileSync(
  `${import.meta.dirname}/../src/lib/data/region-names.svelte.js`,
  `// Generated by scripts/region-names.ts, do not edit.\n/** Names of the regions in the current language, by \`nameId\` */\n/** @returns {string[]} */\nexport function regionNames() {\n  return [\n${items}\n  ];\n}\n`,
);

const po = (lang: string) => `${import.meta.dirname}/../src/locales/${lang}.po`;
for (const lang of ["de", "fr", "es", "it", "pt"] as const) {
  if (!existsSync(po(lang))) continue;
  const translations = new Map<string, string>();
  for (const n of names) if (!translations.has(n.en)) translations.set(n.en, n[lang]);
  // msgid "..." followed by an empty msgstr, in the format of wuchale's PO files
  const text = readFileSync(po(lang), "utf8").replace(
    /(msgid ("(?:[^"\\]|\\.)*")\nmsgstr )""/g,
    (whole, start: string, quoted: string) => {
      const translation = translations.get(JSON.parse(quoted));
      return translation ? `${start}${JSON.stringify(translation)}` : whole;
    },
  );
  writeFileSync(po(lang), text);
}
