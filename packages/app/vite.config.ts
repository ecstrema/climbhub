import { execSync } from "child_process";
import { cpSync, createReadStream, existsSync, statSync } from "fs";
import { basename, join, normalize, resolve } from "path";
import { fileURLToPath } from "url";
import adapter from "@sveltejs/adapter-static";
import tailwindcss from "@tailwindcss/vite";
import devtoolsJson from "vite-plugin-devtools-json";
import { sveltekit } from "@sveltejs/kit/vite";
import { wuchale } from "wuchale/vite";
import { defineConfig, type Plugin } from "vitest/config";

const BASE = "/climbhub";
const API_PREFIX = `${BASE}/api/world/`;
const WORLD_DIR = resolve(fileURLToPath(import.meta.url), "../../climbing-data-gen/build/world");
const API_FILES = new Set(["data.json", "children.json", "stats.json", "download.json"]);

/**
 * The static API is generated by climbing-data-gen: it is never a SvelteKit route, so it is not
 * prerendered. The dev server serves it from the generated folder, and the build copies it.
 */
function climbingApi(): Plugin {
  return {
    name: "climbhub-static-api",
    buildStart() {
      if (existsSync(join(WORLD_DIR, "download.json"))) return;
      execSync("bun run build:climbing-data-gen", { cwd: resolve(WORLD_DIR, "../../../.."), stdio: "inherit" });
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const pathname = decodeURIComponent((req.url ?? "").split("?")[0]!);
        if (!pathname.startsWith(API_PREFIX) || !API_FILES.has(basename(pathname))) return next();

        const file = normalize(join(WORLD_DIR, pathname.slice(API_PREFIX.length)));
        if (!file.startsWith(WORLD_DIR) || !existsSync(file) || !statSync(file).isFile()) return next();

        res.setHeader("content-type", "application/json");
        createReadStream(file).pipe(res);
      });
    },
  };
}

const staticAdapter = adapter();

export default defineConfig({
  plugins: [
    climbingApi(),
    tailwindcss(),
    wuchale(),
    sveltekit({
      // Consult https://kit.svelte.dev/docs/integrations#preprocessors
      // for more information about preprocessors
      preprocess: [],
      adapter: {
        ...staticAdapter,
        async adapt(builder) {
          await staticAdapter.adapt(builder);
          cpSync(WORLD_DIR, join("build", "api", "world"), {
            recursive: true,
            filter: (source) => statSync(source).isDirectory() || API_FILES.has(basename(source)),
          });
        },
      },
      paths: { base: BASE },
      prerender: { concurrency: 8, handleUnseenRoutes: "warn" },
      version: {
        pollInterval: 15 * 60 * 1000 /* 15 minutes */,
        name: execSync("git rev-parse HEAD").toString().trim(),
      },
    }),
    devtoolsJson(),
  ],
  test: { include: ["src/**/*.{test,spec}.{js,ts}"] },
  server: {
    host: "127.0.0.1",
  },
  optimizeDeps: {
    // MapLibre loads its worker from next to its own module: pre-bundling would move the module
    // to .vite/deps without the worker
    exclude: ["maplibre-gl", "@sqlite.org/sqlite-wasm"],
  },
  worker: { format: "es" },
});
