export interface Coordinates {
  lat: number;
  lon: number;
}

export interface OverpassNodeElement {
  type: "node";
  id: number;
  lat: number;
  lon: number;
  tags: Record<string, string>;
}

export interface OverpassWayElement {
  type: "way";
  id: number;
  center: {
    lat: number;
    lon: number;
  };
  nodes: number[];
  tags: Record<string, string>;
}

export interface OverpassRelationElement {
  type: "relation";
  id: number;
  center?: {
    lat: number;
    lon: number;
  };
  members: {
    type: "way" | "relation" | "node";
    ref: number;
    role: string;
  }[];
  tags: Record<string, string>;
}

export type OverpassElement = OverpassNodeElement | OverpassWayElement | OverpassRelationElement;

export interface OverpassRequest {
  version: number;
  generator: string;
  osm3s: {
    timestamp_osm_base: string;
    timestamp_areas_base: string;
    copyright: string;
  };
  elements: OverpassElement[];
}

/** Regions generated by reverse-geocoding-data are of this type*/
export interface GeographicFolderElement {
  type: "geographic";
  name: string;
}

export type DataJSON = OverpassElement | GeographicFolderElement;
