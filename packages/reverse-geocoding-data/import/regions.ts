// The regions imported from OpenStreetMap, by the ISO code of their relation, with their path in
// data/world. A region whose path exists in data/ is neither downloaded nor built again.
//
// Moved after their import (the region is done as long as its original path exists):
// - The Asian subjects of russia (Ural, Siberian and Far Eastern federal districts) are in
//   asia/russia, the others in europe/russia.

export interface Region {
  /** ISO3166-2 tag of the OSM relation. Without "-", ISO3166-1: a whole country */
  code: string;
  /** In data/world, without the extension */
  path: string;
  /**
   * The admin_level of the subdivisions: the region is a group of the ones inside it, named after
   * their `name:<lang>`. A region with a single subdivision (Berlin, Madrid...) is a leaf.
   */
  children?: string;
  lang?: string;
  /** The OSM relation, for the regions without a usable ISO code. `code` only names the region then */
  osm?: number;
}

/** The regions of one country. `codes`: the ISO code (without the country prefix) → slug */
function country(
  path: string,
  prefix: string,
  codes: Record<string, string>,
  options: { children?: string; lang?: string } = {},
): Region[] {
  return Object.entries(codes).map(([code, slug]) => ({
    code: `${prefix}-${code}`,
    path: `${path}/${slug}`,
    ...options,
  }));
}

/**
 * Whole countries of a continent, by ISO3166-1 code → slug. With `children`, a country is a group of
 * its subdivisions of this admin_level (named in English), else a leaf.
 */
function countries(continent: string, codes: Record<string, string | [string, string]>): Region[] {
  return Object.entries(codes).map(([code, value]) => {
    const [slug, children] = typeof value === "string" ? [value] : value;
    return { code, path: `${continent}/${slug}`, ...(children && { children }) };
  });
}

